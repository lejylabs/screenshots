"""Generate independent LittleCMS 2.19 RGB test vectors, never moxcms values."""
import ctypes as c
import ctypes.util
import json
from pathlib import Path
import struct
import zlib

out = Path('crates/app-core/tests/fixtures/color')
out.mkdir(parents=True, exist_ok=True)
lcms = c.CDLL(ctypes.util.find_library('lcms2'))
class xyY(c.Structure):
    _fields_ = [('x', c.c_double), ('y', c.c_double), ('Y', c.c_double)]
class Triple(c.Structure):
    _fields_ = [('r', xyY), ('g', xyY), ('b', xyY)]
lcms.cmsBuildParametricToneCurve.argtypes = [c.c_void_p,c.c_int,c.POINTER(c.c_double)]
lcms.cmsBuildParametricToneCurve.restype = c.c_void_p
lcms.cmsCreateRGBProfile.argtypes = [c.POINTER(xyY),c.POINTER(Triple),c.POINTER(c.c_void_p)]
lcms.cmsCreateRGBProfile.restype = c.c_void_p
lcms.cmsCreate_sRGBProfile.restype = c.c_void_p
lcms.cmsSaveProfileToMem.argtypes = [c.c_void_p,c.c_void_p,c.POINTER(c.c_uint32)]
lcms.cmsCreateTransform.argtypes = [c.c_void_p,c.c_uint32,c.c_void_p,c.c_uint32,c.c_uint32,c.c_uint32]
lcms.cmsCreateTransform.restype = c.c_void_p
lcms.cmsDoTransform.argtypes = [c.c_void_p,c.c_void_p,c.c_void_p,c.c_uint32]
lcms.cmsDeleteTransform.argtypes = [c.c_void_p]
lcms.cmsCloseProfile.argtypes = [c.c_void_p]
lcms.cmsFreeToneCurve.argtypes = [c.c_void_p]
curve = lcms.cmsBuildParametricToneCurve(None,4,(c.c_double*5)(2.4,1/1.055,0.055/1.055,1/12.92,0.04045))
p3 = lcms.cmsCreateRGBProfile(c.byref(xyY(.3127,.329,1)),c.byref(Triple(xyY(.68,.32,1),xyY(.265,.69,1),xyY(.15,.06,1))),(c.c_void_p*3)(curve,curve,curve))
srgb = lcms.cmsCreate_sRGBProfile()
for name, profile in [('lcms-display-p3.icc',p3),('lcms-srgb.icc',srgb)]:
    size=c.c_uint32(); assert lcms.cmsSaveProfileToMem(profile,None,c.byref(size))
    data=c.create_string_buffer(size.value); assert lcms.cmsSaveProfileToMem(profile,data,c.byref(size))
    (out/name).write_bytes(data.raw[:size.value])
samples = [(65535,0,0),(0,65535,0),(0,0,65535),(32768,32768,32768),(20000,40000,30000),(50000,30000,10000),(1,128,255),(257,258,259),(1000,2000,3000),(60000,50000,40000),(12345,34567,23456),(27886,60187,18886)]
alphas = [0,32768,65535,257,12345,65535,0,1,128,32767,65534,50000]
source=(c.c_uint16*(len(samples)*3))(*(v for sample in samples for v in sample))
target=(c.c_uint8*(len(samples)*3))()
transform=lcms.cmsCreateTransform(p3,(4<<16)|(3<<3)|2,srgb,(4<<16)|(3<<3)|1,1,0x0100|0x0040)
assert transform
lcms.cmsDoTransform(transform,source,target,len(samples))
expected = bytes(v for i in range(len(samples)) for v in [*target[i*3:i*3+3],(alphas[i]+128)//257])
(out/'lcms-p3-rgba16-to-srgb8.rgba').write_bytes(expected)
raw = b''.join(b'\0'+b''.join(struct.pack('>4H',*samples[y*3+x],alphas[y*3+x]) for x in range(3)) for y in range(4))
def chunk(kind,data):
    return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data))
png = b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',3,4,16,6,0,0,0))+chunk(b'iCCP',b'P3\0\0'+zlib.compress((out/'lcms-display-p3.icc').read_bytes()))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b'')
(out/'lcms-p3-rgba16.png').write_bytes(png)
hdr = b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',1,1,8,6,0,0,0))+chunk(b'cICP',bytes([9,16,0,1]))+chunk(b'IDAT',zlib.compress(bytes([0,130,170,100,255])))+chunk(b'IEND',b'')
(out/'hdr-pq-cicp.png').write_bytes(hdr)
(out/'README.txt').write_text('Generated by scripts/generate-color-oracle.py using system LittleCMS 2.19.\nDisplay P3 D65 primaries (.68,.32), (.265,.69), (.15,.06), sRGB transfer.\nRGB16 -> RGB8 transform: relative colorimetric, NOOPTIMIZE|NOCACHE.\nAlpha is unassociated and independently quantized by nearest 16/8 conversion.\nNo moxcms code or results are used to calculate these expected values.\nSource tuples: '+repr(samples)+'\nAlpha: '+repr(alphas)+'\nPrivate hdr-pq-cicp.png uses Python stdlib zlib, 1x1 RGBA8 [130,170,100,255], and cICP [9,16,0,1]; it tests refusal, not HDR preservation.\n')
print(json.dumps({'oracle':'LittleCMS 2.19','p3_icc_bytes':(out/'lcms-display-p3.icc').stat().st_size,'expected_rgba':list(expected)}))
lcms.cmsDeleteTransform(transform)
lcms.cmsCloseProfile(p3)
lcms.cmsCloseProfile(srgb)
lcms.cmsFreeToneCurve(curve)
