"""Private RGB8 format-export oracle, calculated with LittleCMS, never moxcms."""
import ctypes as c
import ctypes.util
from pathlib import Path

root = Path(__file__).resolve().parents[1]
out = root / "crates/app-core/tests/fixtures/capture_formats"
out.mkdir(parents=True, exist_ok=True)
profile = (root / "crates/app-core/tests/fixtures/color/lcms-display-p3.icc").read_bytes()
lcms = c.CDLL(ctypes.util.find_library("lcms2"))
lcms.cmsOpenProfileFromMem.argtypes = [c.c_void_p, c.c_uint32]
lcms.cmsOpenProfileFromMem.restype = c.c_void_p
lcms.cmsCreate_sRGBProfile.restype = c.c_void_p
lcms.cmsCreateTransform.argtypes = [c.c_void_p, c.c_uint32, c.c_void_p, c.c_uint32, c.c_uint32, c.c_uint32]
lcms.cmsCreateTransform.restype = c.c_void_p
lcms.cmsDoTransform.argtypes = [c.c_void_p, c.c_void_p, c.c_void_p, c.c_uint32]
lcms.cmsDeleteTransform.argtypes = [c.c_void_p]
lcms.cmsCloseProfile.argtypes = [c.c_void_p]
lcms.cmsGetEncodedCMMversion.restype = c.c_uint32
samples = [(200, 60, 20), (20, 180, 130), (128, 128, 128), (80, 140, 220)]
alpha = [0, 37, 128, 255]
source = (c.c_uint8 * 12)(*(channel for rgb in samples for channel in rgb))
target = (c.c_uint8 * 12)()
memory = c.create_string_buffer(profile)
p3 = lcms.cmsOpenProfileFromMem(memory, len(profile))
srgb = lcms.cmsCreate_sRGBProfile()
assert p3 and srgb
rgb8 = (4 << 16) | (3 << 3) | 1
transform = lcms.cmsCreateTransform(p3, rgb8, srgb, rgb8, 1, 0x0100 | 0x0040)
assert transform
lcms.cmsDoTransform(transform, source, target, len(samples))
expected = bytes(channel for index in range(4) for channel in [*target[index * 3:index * 3 + 3], alpha[index]])
(out / "p3-rgba8-to-srgb8.rgba").write_bytes(expected)
(out / "README.txt").write_text(
    f"Generated by scripts/generate-capture-format-color-oracle.py with system LittleCMS {lcms.cmsGetEncodedCMMversion()}.\n"
    "Uses the genuine matrix Display P3 ICC profile from ../color/lcms-display-p3.icc.\n"
    "RGB8 -> sRGB8, relative colorimetric, NOOPTIMIZE|NOCACHE. Alpha is copied independently.\n"
    "No moxcms code, output or expected values are used. WebP compressed payload is built separately by the Rust fixture.\n"
    f"RGB input: {samples}\nAlpha: {alpha}\n"
)
lcms.cmsDeleteTransform(transform)
lcms.cmsCloseProfile(p3)
lcms.cmsCloseProfile(srgb)
print(f"Wrote {len(expected)} independent synthetic oracle bytes")
